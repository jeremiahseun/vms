import type { MemberStatus, Workspace } from './types';

export const MARKER = '.vws.json';

function expiryLine(ws: Workspace, cliName = 'vws'): string {
  if (!ws.expiresAt) {
    return `**Lifetime:** permanent. Delete any time with \`${cliName} delete ${ws.name}\` (only links are removed, never your projects).`;
  }
  const when = new Date(ws.expiresAt);
  return (
    `**Lifetime:** temporary. Auto-deleted on **${when.toUTCString()}** ` +
    `(only links are removed, never your projects). ` +
    `Keep it with \`${cliName} keep ${ws.name}\` or add time with \`${cliName} extend ${ws.name} 72h\`.`
  );
}

/** Instructions any coding agent (Codex, Claude Code, Gemini, Cursor, ...) reads on start. */
export function agentsMd(ws: Workspace, members: MemberStatus[]): string {
  const rows = members
    .map((m) => {
      const branch = m.branch ? `\`${m.branch}\`` : '(not git)';
      const wt = m.worktree ? ` — worktree of \`${m.worktree.repo}\`` : '';
      return `| \`${m.alias}/\` | \`${m.path}\` | ${branch}${wt} |`;
    })
    .join('\n');
  return `<!-- Generated by VWS. Edits are preserved: VWS stops updating this file once you change it. -->
# Workspace: ${ws.name}

This folder is a **virtual monorepo** built by VWS. Every top-level folder is a link to a
separate project on disk. Reading or editing files here reads or edits the real project directly.

| Folder | Real location | Branch (at last sync) |
| --- | --- | --- |
${rows}

${expiryLine(ws)}

## Rules for coding agents

- **Each folder is its own project/repo.** There is no git repo at this root. Run git from inside a
  project: \`git -C <folder> status\`. Commit, branch and push per project; branches differ.
${
  members.some((m) => m.worktree)
    ? `- **Folders marked "worktree of" are extra checkouts of the same repo on another branch**
  (git worktrees). Commits there land on that branch of the original repo. Don't switch branches
  inside them; each branch can only be checked out in one place.
`
    : ''
}- **Folders are symlinks.** Make search tools follow them: \`rg --follow\`, \`find -L\`,
  \`fd --follow\`, \`grep -R\`. Plain \`rg\`/\`find\` at this root will find nothing.
- **Read each project's own \`AGENTS.md\` / \`CLAUDE.md\` / README** before changing it; its
  conventions win inside that folder.
- Run installs, builds and tests from inside the relevant project folder.
- Cross-project changes (e.g. API + client) are expected: keep them consistent and mention every
  touched project in your summary.
- Don't put files at this root; they belong to no project and are moved to VWS trash on delete.
`;
}

/** Claude Code reads CLAUDE.md; import the shared instructions instead of duplicating them. */
export function claudeMd(): string {
  return `<!-- Generated by VWS -->\n@AGENTS.md\n`;
}

/** Grant Claude Code access to the real paths the links resolve to (avoids permission prompts). */
export function claudeSettings(members: { path: string }[]): string {
  return (
    JSON.stringify(
      { permissions: { additionalDirectories: members.map((m) => m.path) } },
      null,
      2,
    ) + '\n'
  );
}

export function vscodeSettings(members: { alias: string }[]): string {
  return (
    JSON.stringify(
      {
        'search.followSymlinks': true,
        'git.autoRepositoryDetection': true,
        'git.scanRepositories': members.map((m) => m.alias),
        'git.repositoryScanMaxDepth': 1,
        'files.exclude': { [MARKER]: true },
      },
      null,
      2,
    ) + '\n'
  );
}

/** Multi-root file: one root per project (best git + language-server behaviour in VS Code forks). */
export function codeWorkspace(members: { alias: string }[]): string {
  return (
    JSON.stringify(
      {
        folders: members.map((m) => ({ name: m.alias, path: m.alias })),
        settings: { 'search.followSymlinks': true },
      },
      null,
      2,
    ) + '\n'
  );
}

export function managedFiles(ws: Workspace, members: MemberStatus[]): Record<string, string> {
  return {
    'AGENTS.md': agentsMd(ws, members),
    'CLAUDE.md': claudeMd(),
    '.claude/settings.json': claudeSettings(members),
    '.vscode/settings.json': vscodeSettings(members),
    [`${ws.name}.code-workspace`]: codeWorkspace(members),
  };
}
